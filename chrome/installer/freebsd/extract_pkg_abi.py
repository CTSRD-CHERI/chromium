import argparse
import os
import sys
import re

def main():
    # Set up argument parsing
    parser = argparse.ArgumentParser(
        description="Extract a pkg abi macro value from a C/C++ header file using a system root."
    )
    parser.add_argument(
        "--sysroot", 
        help="Absolute or system path to the root directory"
    )
    parser.add_argument(
        "--pkg-arch", 
        required=True, 
        help="The pkg architecture"
    )
    parser.add_argument(
        "--is-cheri", 
        action="store_true",
        help="Enabled if the pkg abi version comes from __CheriBSD"
    )
    parser.add_argument(
        "--output-sh",
        help="Write a shell environment file instead of printing the ABI")
    
    args = parser.parse_args()
    full_path = os.path.join(args.sysroot or "/", "usr/include/sys/param.h")
    
    try:
        with open(full_path, 'r', encoding='utf-8') as f:
            content = f.read()
    except IOError as e:
        print(f"Error: Could not read file at {full_path}: {e}", file=sys.stderr)
        sys.exit(1)
   
    if args.is_cheri:
        match = re.search(r'#\s*define\s+__CheriBSD_version\s+(\d+)', content)
    else:
        match = re.search(r'#\s*define\s+__FreeBSD_version\s+(\d+)', content)
    if not match:
        print(f"Error: Macro pattern not found in {full_path}", file=sys.stderr)
        sys.exit(1)
        
    extracted_value = match.group(1).strip()

    if args.is_cheri:
        pkg_abi = "CheriBSD:" + extracted_value + ":" + args.pkg_arch
    else:
        # Calculate the major version (e.g., 1400097 // 100000 = 14)
        major_version = int(extracted_value) // 100000

        abi_arch = "x86:64" if args.pkg_arch in ("amd64", "x64") else args.pkg_arch
        pkg_abi = f"FreeBSD:{major_version}:{abi_arch}"
 
    if args.output_sh is None:
        print(pkg_abi)
        return

    os.makedirs(os.path.dirname(os.path.abspath(args.output_sh)), exist_ok=True)
    with open(args.output_sh, 'w') as f:
        f.write('# Generated by build. Do not edit.\n')
        f.write(f'PKG_ABI="{pkg_abi}"\n')


if __name__ == '__main__':
    main()
